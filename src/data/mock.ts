/** Timestamp of the last Saturday at hh:mm (never today) */
function lastSaturday(h: number, mi: number) {
  const d = new Date()
  const diff = (d.getDay() - 6 + 7) % 7 || 7
  d.setDate(d.getDate() - diff)
  d.setHours(h, mi, 0, 0)
  return d.getTime()
}
